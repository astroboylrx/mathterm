    this.title = state._hostname + ': ~';
    this.profileId = null;
    this.cwd = window.mathterm.os.homedir();
    this.localCwd = window.mathterm.os.homedir();
    this.displayHost = null;
    this.ptyProc = null;
    this._closing = false;
    this.term = null;
    this.fitAddon = null;
    this.searchAddon = null;
    this.serializeAddon = null;
    this.searchOpen = false;
    this.searchQuery = '';
    this.searchCountText = '';
    this.searchMatches = [];
    this.activeSearchIndex = -1;
    this._searchResultDisposable = null;
    this.richSearchOpen = false;
    this.richSearchQuery = '';
    this.richSearchMatches = [];
    this.richSearchIndex = -1;
    this.richSearchCountText = '';
    this.richSearchNormalizeCache = new Map();
    this.richSearchSource = null;
    this.container = null;
    this.leafEl = null;
    this.xtermHolder = null;
    this.searchHighlightLayer = null;
    this.richView = null;
    this.richContent = null;
    this.richHint = null;
    this.richVisible = false;
